namespace простая_нейросеть_из_одного_нейрона
{
    internal class Neuron
    {
        public double вес { get; private set; }
        public double смещение { get; private set; }
        private static int общийСчётчикОбьектов = 0;
        public int номерНейрона { get; private set; }

        /// <summary>
        /// Конструктор класса Нейрона
        /// </summary>
        /// <param name="вес">Вес нейрона <br></br> (обычно это число на которое умножается Вход)</param>
        /// <param name="смещение">Смещение нейрона <br></br> (обычно это число которое суммируется с результатом всех манипуляций с нейроном)</param>
        public Neuron(double вес, double смещение)
        {
            this.вес = вес;
            this.смещение = смещение;
            номерНейрона = общийСчётчикОбьектов;
            общийСчётчикОбьектов++;
        }

        /// <summary>
        /// Выход одного нейрона от одного выхода.
        /// </summary>
        /// <param name="вход">Вход для нейрона</param>
        /// <returns>Выход нейрона</returns>
        //Пока что не совсем понимаю расширяемость этой функции для несколькоих входов и нескольких нейронов. 
        public double ВычислитьВыход(double вход)
        {
            double выход = вход * вес + смещение;
            return выход;
        } 

        /// <summary>
        /// Прибавляет указаное значание к весу текущего нейрона
        /// </summary>
        /// <param name="изменениеВеса">На сколько изменится вес текущего нейрона</param>
        public void ИзменитьВес(double изменениеВеса)
        {
            this.вес += изменениеВеса;
        }
    }
}