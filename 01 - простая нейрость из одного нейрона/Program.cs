using System;
using System.Collections.Generic;
using static простая_нейросеть_из_одного_нейрона.АлгоритмыОбученияНейросети;

namespace простая_нейросеть_из_одного_нейрона
{
    internal class Program
    {
        //Первоначально создание переменных
        public static double[] средняяОшибкаНейроновПриОбучении = new double[НейронаяСеть.колвоНейронов];
        public static double[][] средняяОшибкаНейроновПриПроверкеНаВходах = new double[НейронаяСеть.колвоНейронов][];
        static void Main(string[] args)
        {
            МетрикиОшибки метрики = new МетрикиОшибки(DataSet.вход, DataSet.правильныеОтветы);
            Обучение(НейронаяСеть.нейроны, метрики, МетрикиОшибки.выборМетодаРасчётаОшибки.MAE);

            //Вывод процесса обучения в консоль
            ЛОГГИ.ОтобразитьЛист(АлгоритмыОбученияНейросети.ченжлог, 0);

            Проверка();
            //Вывод проверок ошибок на новых данных в консоль
            ЛОГГИ.ОтобразитьЛист(АлгоритмыОбученияНейросети.ченжлогОтветов, 1);

        }
        /// <summary>
        /// Сам процесс обучения нейроной сети
        /// </summary>
        /// <param name="нейроны">Все нейроны сети</param>
        /// <param name="метрики">Данные для обучения нейросети, задание и правильный результат решения задания</param>
        /// <param name="выбранныйМетодРасчётаОшибки">Метод оценивания ошибки (из заранее предложеного списка)</param>
        static void Обучение(Neuron[] нейроны, МетрикиОшибки метрики, МетрикиОшибки.выборМетодаРасчётаОшибки выбранныйМетодРасчётаОшибки)
        {
            for (int i = 0; i < нейроны.Length; i++)
            {
                int j = 0;
                double средняяОшибкаНейронаПослеИзменений;
                double средняяОшибкаНейронаПослеИзмененийВеса;
                double средняяОшибкаНейронаПослеИзмененийСмещения;
                double направлениеШагаВеса = 1;
                double направлениеШагаСмещения = 1;
                int счётчикОшибокПодрядВеса = 0;
                int счётчикОшибокПодрядСмещения = 0;
                Neuron.чтоМеняем победитель;
                do
                {
                    double средняяОшибкаНейронаДоИзменений = метрики.методРасчётаОшибки(выбранныйМетодРасчётаОшибки, нейроны[i]);
                    нейроны[i].ИзменитьНейрон(Neuron.чтоМеняем.вес, направлениеШагаВеса * Settings.размерШагаВеса);
                    средняяОшибкаНейронаПослеИзмененийВеса = метрики.методРасчётаОшибки(выбранныйМетодРасчётаОшибки, нейроны[i]);
                    нейроны[i].ИзменитьНейрон(Neuron.чтоМеняем.вес, -направлениеШагаВеса * Settings.размерШагаВеса);
                    нейроны[i].ИзменитьНейрон(Neuron.чтоМеняем.смещение, направлениеШагаСмещения * Settings.размерШагаСмещения);
                    средняяОшибкаНейронаПослеИзмененийСмещения = метрики.методРасчётаОшибки(выбранныйМетодРасчётаОшибки, нейроны[i]);
                    нейроны[i].ИзменитьНейрон(Neuron.чтоМеняем.смещение, -направлениеШагаСмещения * Settings.размерШагаСмещения);

                    (счётчикОшибокПодрядВеса,
                     счётчикОшибокПодрядСмещения,
                     направлениеШагаВеса,
                     направлениеШагаСмещения,
                     j,
                     средняяОшибкаНейронаПослеИзменений,
                     победитель) = АлгоритмыОбученияНейросети.СоравенениеВесаСмещенияИзначальногоРезультата(
                         нейроны[i],
                         средняяОшибкаНейронаДоИзменений,
                         средняяОшибкаНейронаПослеИзмененийВеса,
                         средняяОшибкаНейронаПослеИзмененийСмещения,
                         счётчикОшибокПодрядВеса,
                         счётчикОшибокПодрядСмещения,
                         направлениеШагаВеса,
                         направлениеШагаСмещения,
                         j                         
                     );
                    if (победитель == Neuron.чтоМеняем.вес)
                    {
                        нейроны[i].ИзменитьВес(направлениеШагаВеса * Settings.размерШагаВеса);
                    }
                    else if (победитель == Neuron.чтоМеняем.смещение)
                    {
                        нейроны[i].ИзменитьСмещение(направлениеШагаСмещения * Settings.размерШагаСмещения);
                    }


                    средняяОшибкаНейроновПриОбучении[i] = средняяОшибкаНейронаПослеИзменений;
                }
                while (Settings.допустимаяОшибка <= средняяОшибкаНейронаПослеИзменений && (счётчикОшибокПодрядВеса < 2 || счётчикОшибокПодрядСмещения < 2) && j < 100);
            }
        }
        static void Проверка()
        {
            int колвоДанныхДляПроверки = DataSet.новыеПроверочныеДанные.Length;
            for (int i = 0; i < НейронаяСеть.колвоНейронов; i++)
            {
                ПроверочныеДанные.ПримитивнаяПроверкаНейронаПоАлгоритмуНаНовыхДанных(
                    колвоДанныхДляПроверки, 
                    средняяОшибкаНейроновПриПроверкеНаВходах, 
                    средняяОшибкаНейроновПриОбучении,
                    i);
               }
        }
    }
}