using System;
using System.Collections.Generic;

namespace простая_нейросеть_из_одного_нейрона
{
    internal class Program
    {
        static void Main(string[] args)
        {
            //Первоначально создание переменных
            double желаемыйРезультатНейрона = 20;
            double вход = 5;
            Neuron[] нейроны =
            {
                new Neuron(3, 2),
                new Neuron(4, 2)
            };
            List<string> ченжлог = new List<string>();
            double размерШага = 0.1;


            //Вычисления
            for (int i = 0; i < нейроны.Length; i++)
            {
                int j = 0;
                double ошибкаПослеИзменений;
                do
                {
                    double выходНейронаДоИзменений = нейроны[i].ВычислитьВыход(вход);
                    double ошибкаДоИзменений = Math.Abs(выходНейронаДоИзменений - желаемыйРезультатНейрона);

                    нейроны[i].ИзменитьВес(размерШага);
                    double выходНейронаПослеИзменений = нейроны[i].ВычислитьВыход(вход);
                    ошибкаПослеИзменений = Math.Abs(выходНейронаПослеИзменений - желаемыйРезультатНейрона);

                    string изменениеОшибки;
                    if (ошибкаДоИзменений > ошибкаПослеИзменений)
                    {
                        изменениеОшибки = "Ошибка уменьшилась";
                        ченжлон(ченжлог, изменениеОшибки, нейроны[i], вход, выходНейронаПослеИзменений, желаемыйРезультатНейрона, ошибкаПослеИзменений);
                    }
                    else if (ошибкаДоИзменений < ошибкаПослеИзменений)
                    {
                        изменениеОшибки = "Ошибка увеличилась";
                        нейроны[i].ИзменитьВес(-размерШага);
                        выходНейронаПослеИзменений = нейроны[i].ВычислитьВыход(вход);
                        ошибкаПослеИзменений = Math.Abs(выходНейронаПослеИзменений - желаемыйРезультатНейрона);
                        ченжлон(ченжлог, изменениеОшибки, нейроны[i], вход, выходНейронаПослеИзменений, желаемыйРезультатНейрона, ошибкаПослеИзменений);
                        break;
                    }
                    else
                    {
                        изменениеОшибки = "Ошибка одинаковая";
                        нейроны[i].ИзменитьВес(-размерШага);
                        выходНейронаПослеИзменений = нейроны[i].ВычислитьВыход(вход);
                        ошибкаПослеИзменений = Math.Abs(выходНейронаПослеИзменений - желаемыйРезультатНейрона);
                        ченжлон(ченжлог, изменениеОшибки, нейроны[i], вход, выходНейронаПослеИзменений, желаемыйРезультатНейрона, ошибкаПослеИзменений);
                        break;
                    }
                    j++;
                }
                while (0.1 <= ошибкаПослеИзменений && j < 100);
            }



            //Вывод результатов в консоль
            foreach (string строка_отчёта in ченжлог)
            {
                Console.WriteLine(строка_отчёта);
            }

        }
        public static void ченжлон(List<string> ченжлог, string изменениеОшибки, Neuron нейрон, double вход, double выходНейронаПослеИзменений, double желаемыйРезультатНейрона, double ошибкаПослеИзменений) {
            ченжлог.Add(изменениеОшибки + " у нейрона_" + нейрон.номерНейрона + " \nВход для нейрона = " + вход + " | Вес нейрона = " + нейрон.вес +
                    " | Результат = " + выходНейронаПослеИзменений + " | Желаемый результат " + желаемыйРезультатНейрона + " | Ошибка = " + ошибкаПослеИзменений);
        }

    }
}