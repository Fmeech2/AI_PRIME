using System;
using System.Collections.Generic;

namespace простая_нейросеть_из_одного_нейрона
{
    internal class Program
    {
        //Первоначально создание переменных
        public static double[] вход { get; private set; } = { 2, 4, 100 };
        public static double[] правильныеОтветы { get; private set; } = { 6, 12, 300 };
        public static double[] новыеПроверочныеДанные { get; private set; } = { 10, 1000 };
        public static Neuron[] нейроны { get; private set; } =
            {
                new Neuron(2, 2),
                new Neuron(2, 2),
            };
        public static int колвоНейронов = нейроны.Length;
        public static double[] средняяОшибкаНейроновПриОбучении = new double[колвоНейронов];
        public static double[][] средняяОшибкаНейроновПриПроверкеНаВходах = new double[колвоНейронов][];
        public static double[] средняяОшибкаНейроновПриПроверке { get; private set; } = new double[колвоНейронов];
        public static List<string> ченжлог { get; private set; } = new List<string>();
        public static List<string> ченжлогОтветов { get; private set; } = new List<string>();
        public static double размерШага { get; private set; } = 0.1;
        public static double допустимаяОшибка { get; private set; } = размерШага * 2;
        public const bool ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН = false;
        static void Main(string[] args)
        {
            Обучение();

            //Вывод процесса обучения в консоль
            if (ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН)
            {
                foreach (string строка_отчёта in ченжлог)
                {
                    Console.WriteLine(строка_отчёта);
                }
            }
            Проверка();
            //Вывод проверок ошибок на новых данных в консоль
            Console.WriteLine();
            foreach (string строка_отчёта in ченжлогОтветов)
            {
                Console.WriteLine(строка_отчёта);
            }
        }
        static void Обучение()
        {
            //Вычисления
            for (int i = 0; i < колвоНейронов; i++)
            {
                int j = 0;
                double средняяОшибкаНейронаПослеИзменений;
                double направлениеШага = 1;
                int счётчикОшибокПодряд = 0;
                do
                {
                    double средняяОшибкаНейронаДоИзменений = MAE(нейроны[i]);
                    нейроны[i].ИзменитьВес(направлениеШага * размерШага);
                    средняяОшибкаНейронаПослеИзменений = MAE(нейроны[i]);

                    string изменениеОшибки;
                    if (средняяОшибкаНейронаДоИзменений > средняяОшибкаНейронаПослеИзменений)
                    {
                        изменениеОшибки = "Ошибка уменьшилась";
                            ЗаписатьЧенжлонг();
                        счётчикОшибокПодряд = 0;
                    }
                    else if (средняяОшибкаНейронаДоИзменений < средняяОшибкаНейронаПослеИзменений)
                    {
                        изменениеОшибки = "Ошибка увеличилась";
                        нейроны[i].ИзменитьВес(-размерШага * направлениеШага);
                        направлениеШага = -направлениеШага;
                        средняяОшибкаНейронаПослеИзменений = средняяОшибкаНейронаДоИзменений; //не удалять эту строчку
                        счётчикОшибокПодряд++;
                            ЗаписатьЧенжлонг();
                    }
                    else
                    {
                        изменениеОшибки = "Ошибка одинаковая";
                        нейроны[i].ИзменитьВес(-размерШага * направлениеШага);
                        направлениеШага = -направлениеШага;
                        средняяОшибкаНейронаПослеИзменений = средняяОшибкаНейронаДоИзменений; //не удалять эту строчку
                        счётчикОшибокПодряд++;
                        ЗаписатьЧенжлонг();
                    }
                    j++;
                    void ЗаписатьЧенжлонг()
                    {
                        if (ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН)
                        {
                            ченжлог.Add(изменениеОшибки + " у нейрона_" + нейроны[i].номерНейрона + " итерация обучения " + j +
                            " \n| Вес нейрона = " + нейроны[i].вес + " | Результат средней ошибки = " + средняяОшибкаНейронаПослеИзменений);
                        }
                        средняяОшибкаНейроновПриОбучении[i] = средняяОшибкаНейронаПослеИзменений;
                    }
                }
                while (допустимаяОшибка <= средняяОшибкаНейронаПослеИзменений && счётчикОшибокПодряд < 2 && j < 100);
            }
        }
        static void Проверка()
        {
            int колвоДанныхДляПроверки = новыеПроверочныеДанные.Length;
            for (int i = 0; i < колвоНейронов; i++)
            {
                средняяОшибкаНейроновПриПроверкеНаВходах[i] = new double[колвоДанныхДляПроверки];
                средняяОшибкаНейроновПриПроверке[i] = 0;
                for (int j = 0; j < колвоДанныхДляПроверки; j++)
                {
                    double ошибкаНейронаПриТекущемВводе = Math.Abs(нейроны[i].ВычислитьВыход(новыеПроверочныеДанные[j]) - правильныйОтвет(новыеПроверочныеДанные[j]));
                    средняяОшибкаНейроновПриПроверкеНаВходах[i][j] = ошибкаНейронаПриТекущемВводе;
                    if (ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН)
                    {
                        ченжлогОтветов.Add("Ошибка у нейрона_" + i + " при вводе " + новыеПроверочныеДанные[j] + ": "
                                + ошибкаНейронаПриТекущемВводе + " | ошибка при обучении = " + средняяОшибкаНейроновПриОбучении[i] + " | Весс = " + нейроны[i].вес);
                    }
                }
                for (int j = 0; j < колвоДанныхДляПроверки; j++)
                {
                    средняяОшибкаНейроновПриПроверке[i] += средняяОшибкаНейроновПриПроверкеНаВходах[i][j];
                }
                средняяОшибкаНейроновПриПроверке[i] /= колвоДанныхДляПроверки;
                ченжлогОтветов.Add("Ошибка у нейрона_" + i + " на проверочных данных " + " = "
                            + средняяОшибкаНейроновПриПроверке[i] + " | ошибка при обучении = " + средняяОшибкаНейроновПриОбучении[i] + " | Весс = " + нейроны[i].вес);
            }
            double правильныйОтвет(double x)
            {
                return 3 * x;
            }
        }
        static double MAE(Neuron нейрон)
        {
            int количествоПримеров = вход.Length;
            double суммарнаяОшибка = 0;
            double[] ошибки = new double[правильныеОтветы.Length];
            for (int i = 0; i < количествоПримеров; i++)
            {
                double выход = нейрон.ВычислитьВыход(вход[i]);
                ошибки[i] = Math.Abs(выход - правильныеОтветы[i]);
                суммарнаяОшибка += ошибки[i];
            }
            double средняяОшибка = суммарнаяОшибка / количествоПримеров;
            return средняяОшибка;
        }
    }
}