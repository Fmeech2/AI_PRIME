using System;
using System.Collections.Generic;

namespace простая_нейросеть_из_одного_нейрона
{
    internal class Program
    {
        //Первоначально создание переменных
        public static double[] средняяОшибкаНейроновПриОбучении = new double[НейронаяСеть.колвоНейронов];
        public static double[][] средняяОшибкаНейроновПриПроверкеНаВходах = new double[НейронаяСеть.колвоНейронов][];
        static void Main(string[] args)
        {
            МетрикиОшибки метрики = new МетрикиОшибки(DataSet.вход, DataSet.правильныеОтветы);
            Обучение(НейронаяСеть.нейроны, метрики, МетрикиОшибки.выборМетодаРасчётаОшибки.MAE);

            //Вывод процесса обучения в консоль
            if (Settings.ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН)
            {
                foreach (string строка_отчёта in АлгоритмыОбученияНейросети.ченжлог)
                {
                    Console.WriteLine(строка_отчёта);
                }
            }
            Проверка();
            //Вывод проверок ошибок на новых данных в консоль
            Console.WriteLine();
            foreach (string строка_отчёта in АлгоритмыОбученияНейросети.ченжлогОтветов)
            {
                Console.WriteLine(строка_отчёта);
            }
        }
        static void Обучение(Neuron[] нейроны, МетрикиОшибки метрики, МетрикиОшибки.выборМетодаРасчётаОшибки выбранныйМетодРасчётаОшибки)
        {
            //Вычисления
            for (int i = 0; i < нейроны.Length; i++)
            {
                int j = 0;
                double средняяОшибкаНейронаПослеИзменений;
                double направлениеШага = 1;
                int счётчикОшибокПодряд = 0;
                do
                {
                    double средняяОшибкаНейронаДоИзменений = метрики.методРасчётаОшибки(выбранныйМетодРасчётаОшибки, нейроны[i]);
                    нейроны[i].ИзменитьВес(направлениеШага * Settings.размерШага);
                    средняяОшибкаНейронаПослеИзменений = метрики.методРасчётаОшибки(выбранныйМетодРасчётаОшибки, нейроны[i]);

                    (счётчикОшибокПодряд,
                     направлениеШага,
                     j,
                     средняяОшибкаНейронаПослеИзменений) = АлгоритмыОбученияНейросети.ПростоеСравнени(
                         нейроны[i],
                         средняяОшибкаНейронаДоИзменений, 
                         средняяОшибкаНейронаПослеИзменений, 
                         счётчикОшибокПодряд, 
                         направлениеШага, 
                         j
                     );
                    средняяОшибкаНейроновПриОбучении[i] = средняяОшибкаНейронаПослеИзменений;
                }
                while (Settings.допустимаяОшибка <= средняяОшибкаНейронаПослеИзменений && счётчикОшибокПодряд < 2 && j < 100);
            }
        }
        static void Проверка()
        {
            int колвоДанныхДляПроверки = DataSet.новыеПроверочныеДанные.Length;
            for (int i = 0; i < НейронаяСеть.колвоНейронов; i++)
            {
                ПроверочныеДанные.ПримитивнаяПроверкаНейронаПоАлгоритмуНаНовыхДанных(
                    колвоДанныхДляПроверки, 
                    средняяОшибкаНейроновПриПроверкеНаВходах, 
                    средняяОшибкаНейроновПриОбучении,
                    i);
               }
        }
    }
}