using System;

namespace простая_нейросеть_из_одного_нейрона
{
    internal static class ПроверочныеДанные
    {
        public static double[] новыеПроверочныеДанные { get; private set; } = { 10, 1000 };
        public static double[] средняяОшибкаНейроновПриПроверке { get; private set; } = new double[НейронаяСеть.колвоНейронов];
        public static void ПримитивнаяПроверкаНейронаПоАлгоритмуНаНовыхДанных(
            int колвоДанныхДляПроверки, 
            double[][] средняяОшибкаНейроновПриПроверкеНаВходах, 
            double[] средняяОшибкаНейроновПриОбучении, 
            int i)
        {
            средняяОшибкаНейроновПриПроверкеНаВходах[i] = new double[колвоДанныхДляПроверки];
            средняяОшибкаНейроновПриПроверке[i] = 0;
            for (int j = 0; j < колвоДанныхДляПроверки; j++)
            {
                double ошибкаНейронаПриТекущемВводе = Math.Abs(НейронаяСеть.нейроны[i].ВычислитьВыход(DataSet.новыеПроверочныеДанные[j]) - проверитьПоАлгоритму(DataSet.новыеПроверочныеДанные[j]));
                средняяОшибкаНейроновПриПроверкеНаВходах[i][j] = ошибкаНейронаПриТекущемВводе;
                if (Settings.ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН)
                {
                    АлгоритмыОбученияНейросети.ченжлогОтветов.Add("Ошибка у нейрона_" + i + " при вводе " + DataSet.новыеПроверочныеДанные[j] + ": "
                            + ошибкаНейронаПриТекущемВводе + " | ошибка при обучении = " + средняяОшибкаНейроновПриОбучении[i] + " | Весс = " + НейронаяСеть.нейроны[i].вес);
                }
            }
            for (int j = 0; j < колвоДанныхДляПроверки; j++)
            {
                средняяОшибкаНейроновПриПроверке[i] += средняяОшибкаНейроновПриПроверкеНаВходах[i][j];
            }
            средняяОшибкаНейроновПриПроверке[i] /= колвоДанныхДляПроверки;
            АлгоритмыОбученияНейросети.ченжлогОтветов.Add("Ошибка у нейрона_" + i + " на проверочных данных " + " = "
                        + средняяОшибкаНейроновПриПроверке[i] + " | ошибка при обучении = " + средняяОшибкаНейроновПриОбучении[i] + " | Весс = " + НейронаяСеть.нейроны[i].вес 
                        + " /Итоговое смещение = " + НейронаяСеть.нейроны[i].смещение);
        }

        private static double проверитьПоАлгоритму(double x)
        {
            return 3 * x;
        }
    }
}
