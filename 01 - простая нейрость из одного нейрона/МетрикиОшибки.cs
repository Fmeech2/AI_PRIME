using System;

namespace простая_нейросеть_из_одного_нейрона
{
    internal class МетрикиОшибки
    {
        private readonly double[] вход;
        private readonly double[] правильныеОтветы;

        public МетрикиОшибки(double[] вход, double[] правильныеОтветы)
        {
            this.вход = вход;
            this.правильныеОтветы = правильныеОтветы;
        }

        public enum выборМетодаРасчётаОшибки
        {
            MAE,
            MAPE,
        }
        public double методРасчётаОшибки(
               выборМетодаРасчётаОшибки метод,
               Neuron нейрон)
        {
            switch (метод)
            {
                case выборМетодаРасчётаОшибки.MAE:
                    return MAE(нейрон);
                case выборМетодаРасчётаОшибки.MAPE:
                    return MAPE(нейрон);
                default:
                    return MAE(нейрон);

            }
        }
        /// <summary>
        /// Средняя абсолютная ошибка
        /// </summary>
        /// <param name="нейрон">Отдельный нейрон</param>
        /// <returns>Средняя абсолютная ошибка на обучаемых данных в рассуждениях нейрона по сравненю с правильным ответом</returns>
        public double MAE(Neuron нейрон)
        {
            int количествоПримеров = вход.Length;
            double суммарнаяОшибка = 0;
            double[] ошибки = new double[правильныеОтветы.Length];
            for (int i = 0; i < количествоПримеров; i++)
            {
                double выход = нейрон.ВычислитьВыход(вход[i]);
                ошибки[i] = Math.Abs(выход - правильныеОтветы[i]);
                суммарнаяОшибка += ошибки[i];
            }
            double средняяОшибка = суммарнаяОшибка / количествоПримеров;
            return средняяОшибка;
        }
        /// <summary>
        /// Средняя относительная ошибка
        /// </summary>
        /// <param name="нейрон">Отдельный нейрон</param>
        /// <returns>Средняя относительная ошибка на обучаемых данных в рассуждениях нейрона по сравненю с правильным ответом</returns>
        public double MAPE(Neuron нейрон)
        {
            int количествоПримеров = вход.Length;
            double суммарнаяОшибка = 0;
            double[] ошибки = new double[правильныеОтветы.Length];
            for (int i = 0; i < количествоПримеров; i++)
            {
                double выход = нейрон.ВычислитьВыход(вход[i]);
                ошибки[i] = Math.Abs(выход - правильныеОтветы[i]) / Math.Abs(правильныеОтветы[i]);
                суммарнаяОшибка += ошибки[i];
            }
            double средняяОшибка = суммарнаяОшибка / количествоПримеров;
            return средняяОшибка;
        }
    }
}

