    internal static class АлгоритмыОбученияНейросети
    {
        public static List<string> ченжлог { get; private set; } = new List<string>();
        public static List<string> ченжлогОтветов { get; private set; } = new List<string>();

        //УСТАРЕВШЕЕ
        public static (int, double, int, double) ПростоеСравнениеВеса(
            Neuron нейрон,
            double средняяОшибкаНейронаДоИзменений,
            double средняяОшибкаНейронаПослеИзменений,
            int счётчикОшибокПодряд,
            double направлениеШага,
            int j
            )
        {
            string изменениеОшибки;
            if (средняяОшибкаНейронаДоИзменений > средняяОшибкаНейронаПослеИзменений)
            {
                изменениеОшибки = "Ошибка уменьшилась";
                счётчикОшибокПодряд = 0;
            }
            else if (средняяОшибкаНейронаДоИзменений < средняяОшибкаНейронаПослеИзменений)
            {
                изменениеОшибки = "Ошибка увеличилась";
                нейрон.ИзменитьВес(-Settings.размерШага * направлениеШага);
                направлениеШага = -направлениеШага;
                средняяОшибкаНейронаПослеИзменений = средняяОшибкаНейронаДоИзменений; //не удалять эту строчку
                счётчикОшибокПодряд++;
            }
            else
            {
                изменениеОшибки = "Ошибка одинаковая";
                нейрон.ИзменитьВес(-Settings.размерШага * направлениеШага);
                направлениеШага = -направлениеШага;
                средняяОшибкаНейронаПослеИзменений = средняяОшибкаНейронаДоИзменений; //не удалять эту строчку
                счётчикОшибокПодряд++;
            }
            ЛОГГИ.ЗаписатьЧенжлонг(изменениеОшибки + " у нейрона_" + нейрон.номерНейрона + " итерация обучения " + j +
                " \n| Вес нейрона = " + нейрон.вес + " | Результат средней ошибки = " + средняяОшибкаНейронаПослеИзменений, ченжлог);
            j++;
            return (
                счётчикОшибокПодряд,
                направлениеШага,
                j,
                средняяОшибкаНейронаПослеИзменений
                );
        }
        public static (int, int, double, double, int, double, Neuron.чтоМеняем) СоравенениеВесаСмещенияИзначальногоРезультата(
           Neuron нейрон,
           double средняяОшибкаНейронаДоИзменений,
           double средняяОшибкаНейронаПослеИзмененийВеса,
           double средняяОшибкаНейронаПослеИзмененийСмещения,
           int счётчикОшибокПодрядВеса,
           int счётчикОшибокПодрядСмещения,
           double направлениеШагаВеса,
           double направлениеШагаСмещения,
           int j)
        {
            string изменениеОшибки;
            string изменениеОшибкиВеса;
            string изменениеОшибкиСмещения;
            double средняяОшибкаИтоговая = средняяОшибкаНейронаДоИзменений;
            Neuron.чтоМеняем победитель;

            //я заебался это писать... В будующих апдейтах я снесу это условие и доведу до более компактного вида
            if (средняяОшибкаНейронаПослеИзмененийВеса < средняяОшибкаНейронаДоИзменений)
            {
                if (средняяОшибкаНейронаПослеИзмененийСмещения < средняяОшибкаНейронаДоИзменений)
                {
                    if (средняяОшибкаНейронаПослеИзмененийВеса < средняяОшибкаНейронаПослеИзмененийСмещения)
                    {
                        изменениеОшибки = "Ошибка меньше всего при изменении ВЕСА";
                    средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийВеса; //не удалять эту строчку
                         победитель = Neuron.чтоМеняем.вес;
                    }
                    else if (средняяОшибкаНейронаПослеИзмененийВеса == средняяОшибкаНейронаПослеИзмененийСмещения)
                    {
                        изменениеОшибки = "Ошибка меньше всего при изменении ВЕСА и у СМЕЩЕНИЯ";
                        средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийВеса; //не удалять эту строчку
                         победитель = Neuron.чтоМеняем.вес;
                    }
                    else
                    {
                        изменениеОшибки = "Ошибка меньше всего при изменении СМЕЩЕНИЯ";
                        средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийСмещения; //не удалять эту строчку
                         победитель = Neuron.чтоМеняем.смещение;
                    }
                    изменениеОшибкиВеса = "уменьшилась";
                    изменениеОшибкиСмещения = "уменьшилась";
                    счётчикОшибокПодрядВеса = 0;
                    счётчикОшибокПодрядСмещения = 0;
                }
                else if (средняяОшибкаНейронаПослеИзмененийСмещения == средняяОшибкаНейронаДоИзменений)
                {
                    изменениеОшибки = "Ошибка меньше всего при изменении ВЕСА";
                    изменениеОшибкиВеса = "уменьшилась";
                    изменениеОшибкиСмещения = "одинаковая";
                    направлениеШагаСмещения = -направлениеШагаСмещения;
                    счётчикОшибокПодрядВеса = 0;
                    счётчикОшибокПодрядСмещения ++;
                    средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийВеса; //не удалять эту строчку
                     победитель = Neuron.чтоМеняем.вес;
                }
                else
                {
                    изменениеОшибки = "Ошибка меньше всего при изменении ВЕСА";
                    изменениеОшибкиВеса = "уменьшилась";
                    изменениеОшибкиСмещения = "Увеличилась";
                    направлениеШагаСмещения = -направлениеШагаСмещения;
                    счётчикОшибокПодрядВеса = 0;
                    счётчикОшибокПодрядСмещения++;
                    средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийВеса; //не удалять эту строчку
                    победитель = Neuron.чтоМеняем.вес;
                }
            }
            else if (средняяОшибкаНейронаПослеИзмененийСмещения < средняяОшибкаНейронаДоИзменений)
            {
                if (средняяОшибкаНейронаПослеИзмененийВеса == средняяОшибкаНейронаДоИзменений)
                {
                    изменениеОшибки = "Ошибка меньше всего при изменении СМЕЩЕНИЯ";
                    изменениеОшибкиВеса = "одинаковая";
                    направлениеШагаВеса = -направлениеШагаВеса;
                    изменениеОшибкиСмещения = "уменьшилась";
                    счётчикОшибокПодрядВеса ++;
                    счётчикОшибокПодрядСмещения = 0;
                    средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийСмещения; //не удалять эту строчку
                    победитель = Neuron.чтоМеняем.смещение;
                }
                else
                {
                    изменениеОшибки = "Ошибка меньше всего при изменении СМЕЩЕНИЯ";
                    изменениеОшибкиВеса = "Увеличилась";
                    направлениеШагаВеса = -направлениеШагаВеса;
                    изменениеОшибкиСмещения = "уменьшилась";
                    счётчикОшибокПодрядВеса++;
                    счётчикОшибокПодрядСмещения = 0;
                    средняяОшибкаИтоговая = средняяОшибкаНейронаПослеИзмененийСмещения; //не удалять эту строчку
                    победитель = Neuron.чтоМеняем.смещение;
                }
            }
            else
            {
                if (средняяОшибкаНейронаПослеИзмененийВеса == средняяОшибкаНейронаДоИзменений && средняяОшибкаНейронаПослеИзмененийСмещения == средняяОшибкаНейронаДоИзменений)
                {
                    изменениеОшибки = "Ошибка ОДИНАКОВАЯ";
                    изменениеОшибкиВеса = "одинаковая";
                    изменениеОшибкиСмещения = "одинаковая";
                }
                else if (средняяОшибкаНейронаПослеИзмененийВеса == средняяОшибкаНейронаДоИзменений)
                {
                    изменениеОшибки = "Ошибка меньше всего до изменений и у веса";
                    изменениеОшибкиВеса = "одинаковая";
                    изменениеОшибкиСмещения = "Увеличилась";
                }
                else if (средняяОшибкаНейронаПослеИзмененийСмещения == средняяОшибкаНейронаДоИзменений)
                {
                    изменениеОшибки = "Ошибка меньше всего до изменений и у смещения";
                    изменениеОшибкиВеса = "Увеличилась";
                    изменениеОшибкиСмещения = "одинаковая";
                }
                else
                {
                    изменениеОшибки = "Ошибка меньше всего до изменений";
                    изменениеОшибкиВеса = "Увеличилась";
                    изменениеОшибкиСмещения = "Увеличилась";
                }
                направлениеШагаВеса = -направлениеШагаВеса;
                направлениеШагаСмещения = -направлениеШагаСмещения;
                счётчикОшибокПодрядВеса++;
                счётчикОшибокПодрядСмещения++;
                победитель = Neuron.чтоМеняем.ничего;
            }
            ЛОГГИ.ЗаписатьЧенжлонг(изменениеОшибки + " | у нейрона_" + нейрон.номерНейрона + " итерация обучения " + j +
                " \n| Вес = " + нейрон.вес +"| Смещение = " + нейрон.смещение + " | Результат средней ошибки = " + средняяОшибкаИтоговая, ченжлог);
            j++;
            return (
                счётчикОшибокПодрядВеса,
                счётчикОшибокПодрядСмещения,
                направлениеШагаВеса,
                направлениеШагаСмещения,
                j,
                средняяОшибкаИтоговая,
                победитель
                );
        }
    }
