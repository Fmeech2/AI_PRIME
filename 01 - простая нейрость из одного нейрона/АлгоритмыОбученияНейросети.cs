using System.Collections.Generic;

namespace простая_нейросеть_из_одного_нейрона
{
    internal static class АлгоритмыОбученияНейросети
    {
        public static List<string> ченжлог { get; private set; } = new List<string>();
        public static List<string> ченжлогОтветов { get; private set; } = new List<string>();
        public static (int, double, int, double) ПростоеСравнени(
            Neuron нейрон,
            double средняяОшибкаНейронаДоИзменений,
            double средняяОшибкаНейронаПослеИзменений,
            int счётчикОшибокПодряд,
            double направлениеШага,
            int j)
        {
            string изменениеОшибки;
            if (средняяОшибкаНейронаДоИзменений > средняяОшибкаНейронаПослеИзменений)
            {
                изменениеОшибки = "Ошибка уменьшилась";
                ЗаписатьЧенжлонг();
                счётчикОшибокПодряд = 0;
            }
            else if (средняяОшибкаНейронаДоИзменений < средняяОшибкаНейронаПослеИзменений)
            {
                изменениеОшибки = "Ошибка увеличилась";
                нейрон.ИзменитьСмещение(-Settings.размерШага * направлениеШага);
                направлениеШага = -направлениеШага;
                средняяОшибкаНейронаПослеИзменений = средняяОшибкаНейронаДоИзменений; //не удалять эту строчку
                счётчикОшибокПодряд++;
                ЗаписатьЧенжлонг();
            }
            else
            {
                изменениеОшибки = "Ошибка одинаковая";
                нейрон.ИзменитьСмещение(-Settings.размерШага * направлениеШага);
                направлениеШага = -направлениеШага;
                средняяОшибкаНейронаПослеИзменений = средняяОшибкаНейронаДоИзменений; //не удалять эту строчку
                счётчикОшибокПодряд++;
                ЗаписатьЧенжлонг();
            }
            j++;
            void ЗаписатьЧенжлонг()
            {
                if (Settings.ЧЕНЖЛОГ_КАЖДОГО_НЕЙРОНА_ВКЛЮЧЕН)
                {
                    ченжлог.Add(изменениеОшибки + " у нейрона_" + нейрон.номерНейрона + " итерация обучения " + j +
                    " \n| Вес нейрона = " + нейрон.вес + " | Результат средней ошибки = " + средняяОшибкаНейронаПослеИзменений);
                }
            }
            return (
                счётчикОшибокПодряд,
                направлениеШага,
                j,
                средняяОшибкаНейронаПослеИзменений
                );
        }
    }
}
